# -*- coding: utf-8 -*-
"""
==========================================================================
 工程根目录工具（新人阅读顺序：第 12 个）
==========================================================================

【一句话说明】
    提供 get_cwd()，返回**本文件所在目录**，也就是工程根目录。
    之所以单独抽一个文件，是为了避免各个模块用一堆 ../.. 去猜路径。

【在框架中的位置】
    被 Common/basePage.py、Common/config.py、Common/log.py 导入使用。
    注意：本文件必须放在工程根目录，位置一变所有相对路径都会失效。

【新人注意】
    - 返回的是"本文件所在目录"而不是"当前工作目录"（os.getcwd()），
      所以无论从哪个目录启动 python，路径都稳定。
    - 新增需要定位工程根的模块时，统一 `import getcwd` 后调用 get_cwd()，
      不要再自己拼 os.path.dirname(...)。
==========================================================================
"""

import os


def get_cwd():
    """返回工程根目录的绝对路径（即本文件所在目录）。"""
    # __file__ 是当前 .py 文件的路径；abspath 转绝对路径；dirname 取所在目录
    path = os.path.dirname(os.path.abspath(__file__))
    return path
